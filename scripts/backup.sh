#!/usr/bin/env bash
# ============================================================
#  backup.sh — back up the things that hurt to lose.
#
#  Configs, secrets and database dumps: small, and weeks of work to
#  redo. NOT media (large, re-obtainable). Your photo files go only
#  into the off-site copy, when you set one up: docs/backups.md.
#
#    ./scripts/backup.sh --dry-run     show the plan, write nothing
#    ./scripts/backup.sh               run it
#    ./scripts/backup.sh /mnt/usb      back up somewhere else
#    ./scripts/backup.sh --local-only  skip the off-site copy
#
#  Off-site: OFFSITE_REPO and OFFSITE_PASSWORD in .env add an
#  encrypted copy (restic, in a container) after the local one.
#  Exits non-zero if anything failed, so cron can alert on it.
# ============================================================
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1
. lib/detect.sh
. lib/offsite.sh

DRY_RUN=0; DEST=""; LOCAL_ONLY=0
for a in "$@"; do case "$a" in
  --dry-run) DRY_RUN=1 ;;
  --local-only) LOCAL_ONLY=1 ;;
  -h|--help) sed -n '2,/^# ===/s/^# \{0,2\}//p' "scripts/${0##*/}"; exit 0 ;;
  -*) echo "unknown option: $a" >&2; exit 2 ;;
  *) DEST="$a" ;;
esac; done

ENV_FILE="${ENV_FILE:-.env}"
[ -r "$ENV_FILE" ] || { echo "No $ENV_FILE — run ./setup.sh first." >&2; exit 1; }
# Off-site settings come from .env only, never from the shell's own
# environment.
unset OFFSITE_REPO OFFSITE_PASSWORD OFFSITE_PHOTOS
set -a
# shellcheck source=/dev/null  # .env is generated by setup.sh, not in the repo
. "./$ENV_FILE"
set +a

DEST="${DEST:-${BACKUP_DEST:-}}"
if [ -z "$DEST" ]; then
  echo "No destination. Pass one, or set BACKUP_DEST in .env:" >&2
  echo "  ./scripts/backup.sh /mnt/backup-drive" >&2
  exit 1
fi

STAMP="$(date +%F)"
OUT="${DEST}/${STAMP}"
RETAIN_DAYS="${BACKUP_RETAIN_DAYS:-30}"
FAILED=0; CHANGED=0; REMOVED=0
fail() { printf '  %s%s FAILED%s  %s\n' "$C_ERR" "$S_ERR" "$C_RST" "$1"; FAILED=1; }
wrn()  { warn "$1"; }
good() { ok "$1"; }

# ============================================================
#  tar's verdict. GNU tar exits 1 when files changed while it read
#  them, and 2 on a real error (tar manual, "Synopsis"). Exit 1 is
#  only a warning when every message is one of these two:
#    "file changed as we read it"      an app was writing to it
#    "File removed before we read it"  an app deleted it (a temp file):
#                                      no part of it is in the archive
#  Anything else, such as "File shrank" (zeros where data was), or any
#  other exit, is a failure. tar translates its messages, so it runs
#  under LC_ALL=C. Its messages name files and errors, never contents.
#    tar_run <command...>   0 clean, 1 changed/removed only, 2 failed
#  The messages are left in TAR_MSGS, the exit code in TAR_RC.
# ============================================================
TAR_MSGS=""; TAR_RC=0
TAR_CHANGED=': file changed as we read it$'
TAR_REMOVED=': File removed before we read it$'
tar_run() {
  TAR_MSGS="$(LC_ALL=C "$@" 2>&1 >/dev/null)"; TAR_RC=$?
  TAR_MSGS="$(grep -v '^tar: Exiting with failure status due to previous errors$' <<< "$TAR_MSGS")"
  [ "$TAR_RC" -eq 0 ] && return 0
  if [ "$TAR_RC" -eq 1 ] && [ -n "$TAR_MSGS" ] \
     && ! grep -qv -e "^tar: .*$TAR_CHANGED" -e "^tar: .*$TAR_REMOVED" <<< "$TAR_MSGS"; then
    return 1
  fi
  return 2
}

tar_lines() {   # up to 10 lines of TAR_MSGS through sed $1, as notes
  local n
  n="$(sed "$1" <<< "$TAR_MSGS" | grep -c .)"
  sed "$1" <<< "$TAR_MSGS" | head -n 10 | while IFS= read -r l; do note "  $l"; done
  [ "$n" -gt 10 ] && note "  ... and $((n - 10)) more"
}

tar_warned() {   # the warnings, naming the files: changed, then deleted
  local c r
  c="$(grep -c "$TAR_CHANGED" <<< "$TAR_MSGS")"
  r="$(grep -c "$TAR_REMOVED" <<< "$TAR_MSGS")"
  CHANGED=$((CHANGED + c)); REMOVED=$((REMOVED + r))
  if [ "$c" -gt 0 ]; then
    wrn "$1: written, but these changed while tar read them:"
    tar_lines "/$TAR_CHANGED/!d; s/^tar: \(.*\)$TAR_CHANGED/\1/"
    note "An app was writing to them, so their copy may not match itself."
    note "A database copied mid-write can fail to open when restored."
  fi
  if [ "$r" -gt 0 ]; then
    wrn "$1: written; these were deleted while tar read them:"
    tar_lines "/$TAR_REMOVED/!d; s/^tar: \(.*\)$TAR_REMOVED/\1/"
    note "An app removed them mid-backup, usually a temporary file such as"
    note "a database's -journal. The archive holds no half-copy of them."
  fi
  note "docs/backups.md, Traps: \"Live databases\"."
}

tar_failed() {   # the failure, with tar's own reason
  fail "$1 (tar exit $TAR_RC)"
  if [ -n "$TAR_MSGS" ]; then tar_lines 's/^tar: //'; else note "  tar printed no reason"; fi
}

# ============================================================
#  Where is it going? The most important question here.
# ============================================================
h1 "Destination"
kv "Target" "$OUT"
SRC_FS="$(fs_of "$APPDATA" 2>/dev/null)"
[ "$DRY_RUN" -eq 1 ] || mkdir -p "$DEST" 2>/dev/null
# df needs a path that exists. A dry run creates nothing, so measure the
# nearest folder that does; the backup lands on the same filesystem.
AT="$DEST"
while [ ! -d "$AT" ]; do AT="$(dirname "$AT")"; done
[ "$AT" = "$DEST" ] || note "not there yet: a real run creates it (measured at $AT)"
DST_FS="$(fs_of "$AT" 2>/dev/null)"
kv "Free there" "$(free_gb "$AT" 2>/dev/null) GB"

if [ -n "$SRC_FS" ] && [ "$SRC_FS" = "$DST_FS" ]; then
  wrn "Backup destination is on the SAME filesystem as your data."
  note "This protects you from: deleting a file, a bad config, a failed"
  note "upgrade. It does NOT protect you from the thing most likely to"
  note "actually happen — that disk dying. When it goes, it takes your"
  note "only copy with it."
  note ""
  note "Treat this as step one, not as done. A cheap USB disk is a real"
  note "improvement; somewhere outside the building is the real answer."
else
  good "destination is on a different filesystem from your data"
fi

# ============================================================
#  Databases: dump them, never tar them live.
#    service|container|type|user|dbname
# ============================================================
DATABASES="
immich|immich-db|pg|${IMMICH_DB_USER:-immich}|${IMMICH_DB_NAME:-immich}
"

# ============================================================
#  Caches and regenerable data — excluded on purpose.
#  These rebuild themselves and dominate the archive size.
#  So do a running database's own files: copied mid-write they may
#  not start, and its dump (DATABASES) is the real copy.
# ============================================================
EXCLUDES=(
  --exclude=jellyfin/config/data/metadata     # re-fetchable artwork, can be GBs
  --exclude=jellyfin/config/cache
  --exclude=jellyfin/config/log
  --exclude=jellyfin/transcode                # scratch space
  --exclude=immich/model-cache                # re-downloadable ML models
  --exclude=immich/postgres                   # Immich's database files: dumped instead
  --exclude=calibre-web/config/processed_books # re-convertible copies, can be GBs
  --exclude=calibre-web/config/thumbnails
  --exclude='*/logs/*.log'
  --exclude='*/log/*.log'
)

h1 "Plan"
SERVICES="$(echo "${COMPOSE_PROFILES:-}" | tr ',' ' ')"
# Where a service keeps its config under appdata, when it isn't <key>.
# "-" = nothing to keep: no config at all, or only a cache.
# (setup.sh makes an empty appdata/<key> for every service, so a
# directory existing is no proof that it holds anything.)
appdir_of() {
  case "$1" in
    nginx-proxy-manager) echo npm ;;
    dozzle|immich-ml)    echo - ;;
    *)                   echo "$1" ;;
  esac
}
HAVE=(); MISSING=(); NOCONF=()
for s in $SERVICES; do
  d="$(appdir_of "$s")"
  if [ "$d" = "-" ]; then NOCONF+=("$s")
  elif [ -d "${APPDATA}/${d}" ]; then HAVE+=("$d")
  else MISSING+=("$s"); fi
done

echo "  config dirs:   ${#HAVE[@]} of $(wc -w <<< "$SERVICES") installed services"
[ "${#NOCONF[@]}" -gt 0 ] && note "no config to keep: ${NOCONF[*]}"
[ "${#MISSING[@]}" -gt 0 ] && note "no appdata yet (normal if never started): ${MISSING[*]}"
DUMPS=0
for row in $DATABASES; do
  svc="${row%%|*}"
  case " $SERVICES " in *" $svc "*) DUMPS=$((DUMPS+1)) ;; esac
done
echo "  database dumps: $DUMPS"
echo "  also:           .env, compose files, your stack definition"

# The stack archive is this folder, so anything else that lives in it
# would be copied too: setup.sh's defaults put media and photos here,
# and a destination here would take in every earlier backup. tar names
# what it reads ./<path>, so each one is left out by its path from here,
# resolved (setup.sh writes absolute paths), and only when inside.
HERE="$(pwd -P)"
inside_here() {   # inside_here <path> -> ./<path from here>, or fails
  local p
  [ -n "$1" ] || return 1
  p="$(realpath -m -- "$1" 2>/dev/null)" || return 1
  case "$p" in "$HERE"/?*) printf './%s\n' "${p#"$HERE"/}" ;; *) return 1 ;; esac
}
# ------------------------------------------------- the off-site copy
# Checked before anything is written, so a mistake in .env costs nothing.
OFFSITE=0; OFF_PHOTOS=0
if [ -n "${OFFSITE_REPO:-}" ] && [ "$LOCAL_ONLY" -eq 0 ]; then
  OFFSITE=1
  offsite_is_dir "$OFFSITE_REPO" || { offsite_not_dir; exit 1; }
  [ -n "${OFFSITE_PASSWORD:-}" ] \
    || { err "OFFSITE_REPO is set, but OFFSITE_PASSWORD is empty (docs/backups.md)."; exit 1; }
  case "${OFFSITE_PHOTOS:-yes}" in
    yes) case " $SERVICES " in *" immich "*) [ -n "${PHOTOS_LOCATION:-}" ] && OFF_PHOTOS=1 ;; esac ;;
    no) ;;
    *) err "OFFSITE_PHOTOS is '${OFFSITE_PHOTOS}': yes or no."; exit 1 ;;
  esac
fi

SKIP=(); SKIP_ARGS=()
REPO_PATH=""; [ "$OFFSITE" -eq 1 ] && REPO_PATH="$OFFSITE_REPO"
for p in "${MEDIA_ROOT:-}" "${PHOTOS_LOCATION:-}" "$DEST" "$REPO_PATH"; do
  r="$(inside_here "$p")" || continue
  SKIP+=("$r"); SKIP_ARGS+=("--exclude=$r")
done
[ "${#SKIP[@]}" -gt 0 ] && note "left out of the stack archive (inside this folder): ${SKIP[*]}"
echo "  NOT backed up:  ${MEDIA_ROOT:-./media} (large and re-obtainable)"
case " $SERVICES " in *" immich "*)
  if [ "$OFF_PHOTOS" -eq 1 ]; then
    echo "  off-site only:  ${PHOTOS_LOCATION} (your photo files)"
    note "Immich's database is dumped here; the photos go to the off-site copy."
  else
    echo "  NOT backed up:  ${PHOTOS_LOCATION:-./photos} (your photo files)"
    note "Immich's database is dumped; the photos it points at are not."
    note "Copy them yourself after this: docs/backups.md, \"Your photos\"."
  fi ;;
esac
if [ "$OFFSITE" -eq 1 ]; then
  echo "  off-site:       $OFFSITE_REPO, encrypted ($RESTIC_IMAGE)"
  AT="$OFFSITE_REPO"; while [ ! -d "$AT" ]; do AT="$(dirname "$AT")"; done
  if [ -n "$SRC_FS" ] && [ "$(fs_of "$AT" 2>/dev/null)" = "$SRC_FS" ]; then
    wrn "the off-site repository is on the SAME filesystem as your data."
    note "It is encrypted, but it dies with that disk. Point OFFSITE_REPO"
    note "at another disk, or at a share on another machine."
  fi
elif [ "$LOCAL_ONLY" -eq 1 ] && [ -n "${OFFSITE_REPO:-}" ]; then
  echo "  off-site:       skipped (--local-only)"
else
  echo "  off-site:       none (OFFSITE_REPO in .env, docs/backups.md)"
fi

if [ "$DRY_RUN" -eq 1 ]; then
  echo
  printf '%s  DRY RUN — nothing written.%s\n' "$C_WARN" "$C_RST"
  exit 0
fi

mkdir -p "$OUT" || { echo "cannot create $OUT" >&2; exit 1; }

# ============================================================
#  Root-owned files. Use `sudo -n` so cron can never hang on a
#  password prompt. Probe with a real command: a command-scoped
#  sudoers entry refuses `sudo -n true` even when tar is allowed.
# ============================================================
SUDO=()
if sudo -n /usr/bin/tar --version >/dev/null 2>&1; then
  SUDO=(sudo -n); good "passwordless sudo available (root-owned files included)"
else
  wrn "no passwordless sudo — root-owned config files will be SKIPPED."
  note "Some services write config as root. Without sudo those files are"
  note "silently missing from the archive, and you find out at restore"
  note "time. To fix, allow tar without a password:"
  note "  echo \"\$USER ALL=(root) NOPASSWD: /usr/bin/tar\" | sudo tee /etc/sudoers.d/backup"
fi

# ---------------------------------------------------------- databases
h1 "Databases"
if [ "$DUMPS" -eq 0 ]; then
  good "none installed"
else
  for row in $DATABASES; do
    IFS='|' read -r svc cont _ user db <<< "$row"
    case " $SERVICES " in *" $svc "*) ;; *) continue ;; esac
    c="${STACK_PREFIX}${cont}"
    if ! docker ps --format '{{.Names}}' | grep -qx "$c"; then
      fail "$svc: container $c is not running — cannot dump"
      continue
    fi
    f="${svc}-db.sql.gz"
    if ! docker exec "$c" pg_dump -U "$user" "$db" 2>/dev/null | gzip > "$OUT/$f"; then
      fail "$svc: pg_dump failed"
      continue
    fi
    # Judge a dump by whether it contains schema, not by byte size - a
    # 400-byte dump of an empty database is correct; a 400-byte dump of
    # a full one is a disaster, and both pass a size check.
    n="$(gzip -dc "$OUT/$f" 2>/dev/null | grep -c '^CREATE TABLE' || true)"
    if [ "${n:-0}" -eq 0 ]; then
      wrn "$svc: dump has no tables — empty database, or a broken dump"
    else
      good "$svc: $n tables -> $f"
    fi
  done
fi

# ------------------------------------------------------------ configs
h1 "Configs"
if [ "${#HAVE[@]}" -eq 0 ]; then
  wrn "no appdata directories found — nothing to archive"
else
  tar_run "${SUDO[@]}" tar czf "$OUT/appdata-configs.tar.gz" \
    -C "$APPDATA" "${EXCLUDES[@]}" "${HAVE[@]}"; rc=$?
  [ "${#SUDO[@]}" -gt 0 ] && [ -e "$OUT/appdata-configs.tar.gz" ] \
    && sudo -n /usr/bin/chown "$(id -u):$(id -g)" "$OUT/appdata-configs.tar.gz" 2>/dev/null
  case "$rc" in
    0) good "appdata-configs.tar.gz ($(du -h "$OUT/appdata-configs.tar.gz" | cut -f1)) — ${#HAVE[@]} services" ;;
    1) tar_warned "appdata-configs.tar.gz" ;;
    *) tar_failed "could not archive configs" ;;
  esac
fi

# ----------------------------------------------------------- the stack
h1 "Stack definition"
# Includes .env, which holds every secret. Hence mode 600.
tar_run tar czf "$OUT/stack.tar.gz" --exclude='./appdata' --exclude='./testdata' \
  --exclude='./.git' --exclude="$OFFSITE_CACHE" --anchored --no-wildcards "${SKIP_ARGS[@]}" -C . .; rc=$?
[ -e "$OUT/stack.tar.gz" ] && chmod 600 "$OUT/stack.tar.gz"
case "$rc" in
  0) good "stack.tar.gz ($(du -h "$OUT/stack.tar.gz" | cut -f1)) — includes .env, mode 600" ;;
  1) tar_warned "stack.tar.gz" ;;
  *) tar_failed "could not archive the stack" ;;
esac

# ------------------------------------------------------------ retention
h1 "Retention"
OLD="$(find "$DEST" -maxdepth 1 -type d -name '20*-*-*' -mtime "+${RETAIN_DAYS}" 2>/dev/null | wc -l)"
if [ "${OLD:-0}" -gt 0 ]; then
  find "$DEST" -maxdepth 1 -type d -name '20*-*-*' -mtime "+${RETAIN_DAYS}" -exec rm -rf {} + 2>/dev/null
  good "removed $OLD backup(s) older than ${RETAIN_DAYS} days"
else
  good "nothing older than ${RETAIN_DAYS} days"
fi

# ----------------------------------------------------- off-site copy
# restic stores today's folder (and the photos) encrypted, as one
# snapshot; only what changed since the last one is sent. A local
# backup with failures is not sent: it would count as a good copy.
OFF_SAVED=""
offsite_copy() {
  local rc mounts paths
  if [ ! -d "$OFFSITE_REPO" ]; then
    mkdir -p "$OFFSITE_REPO" || { fail "off-site: cannot create $OFFSITE_REPO"; return; }
  fi
  offsite_run -- cat config > /dev/null; rc=$?
  if [ "$rc" -eq 10 ]; then
    offsite_run -- init; rc=$?
    [ "$rc" -eq 0 ] || { fail "off-site: could not create the repository ($(offsite_why "$rc"))"; tail -n 5 <<< "$OFFSITE_OUT" | offsite_lines; return; }
    good "created an encrypted repository at $OFFSITE_REPO"
    note "Keep OFFSITE_PASSWORD somewhere off this machine too (a password"
    note "manager, paper). Without it this copy can never be read."
  elif [ "$rc" -ne 0 ]; then
    fail "off-site: $(offsite_why "$rc")"; tail -n 5 <<< "$OFFSITE_OUT" | offsite_lines; return
  fi
  mounts=(-v "$(realpath -- "$OUT"):/anteiku/backup:ro"); paths=(/anteiku/backup)
  if [ "$OFF_PHOTOS" -eq 1 ]; then
    if [ -d "$PHOTOS_LOCATION" ]; then
      mounts+=(-v "$(realpath -- "$PHOTOS_LOCATION"):/anteiku/photos:ro"); paths+=(/anteiku/photos)
    else
      wrn "off-site: $PHOTOS_LOCATION does not exist, photos not sent"
    fi
  fi
  offsite_run "${mounts[@]}" -- backup "${paths[@]}" --host "$OFFSITE_HOST" --tag anteiku; rc=$?
  case "$rc" in
    0) OFF_SAVED="$(sed -n 's/^snapshot \([0-9a-f]*\) saved$/\1/p' <<< "$OFFSITE_OUT")"
       good "snapshot ${OFF_SAVED:-?} saved ($(sed -n 's/^Added to the repository: //p' <<< "$OFFSITE_OUT") added)" ;;
    3) fail "off-site: some files could not be read; the copy is incomplete"
       grep -i 'error\|denied' <<< "$OFFSITE_OUT" | head -n 10 | offsite_lines ;;
    *) fail "off-site: backup failed ($(offsite_why "$rc"))"; tail -n 10 <<< "$OFFSITE_OUT" | offsite_lines ;;
  esac
  [ "$rc" -eq 0 ] || return
  offsite_run -- forget --host "$OFFSITE_HOST" --tag anteiku "${OFFSITE_KEEP[@]}" --prune; rc=$?
  if [ "$rc" -eq 0 ]; then good "old snapshots pruned (kept: 7 daily, 5 weekly, 12 monthly)"
  else wrn "off-site: old snapshots not pruned ($(offsite_why "$rc")); the new one is saved"; fi
}
if [ "$OFFSITE" -eq 1 ]; then
  h1 "Off-site copy"
  if [ "$FAILED" -ne 0 ]; then wrn "skipped: the local backup failed (above)"
  elif ! have docker; then fail "off-site: Docker is not installed (restic runs in a container)"
  else offsite_copy; fi
fi

# -------------------------------------------------------------- report
h1 "Result"
# shellcheck disable=SC2012  # display only; the names are ours
ls -lh "$OUT" 2>/dev/null | tail -n +2 | awk '{printf "  %-28s %s\n", $9, $5}'
echo
TOTAL="$(du -sh "$OUT" 2>/dev/null | cut -f1)"
if [ "$FAILED" -eq 0 ]; then
  printf '  %sBackup complete%s — %s in %s\n' "$C_OK" "$C_RST" "$TOTAL" "$OUT"
  [ "$CHANGED" -gt 0 ] && warn "$CHANGED file(s) changed while being read: see the warning above."
  [ "$REMOVED" -gt 0 ] && warn "$REMOVED file(s) deleted while being read: see the warning above."
  [ -n "$OFF_SAVED" ] && good "off-site copy saved: snapshot $OFF_SAVED"
  echo
  note "Untested backups are not backups. See docs/backups.md for how to"
  note "verify this one — it takes five minutes and is the only way to"
  note "know it works."
else
  printf '  %sBackup finished WITH FAILURES%s — read the lines above.\n' "$C_ERR" "$C_RST"
fi
exit "$FAILED"
