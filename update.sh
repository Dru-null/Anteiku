#!/usr/bin/env bash
# ============================================================
#  update.sh — move this install to the newest tested release.
#
#    ./update.sh --check       is there one? Changes nothing.
#                              Exit 0 up to date, 1 update available.
#    ./update.sh               back up, update, restart. Asks first
#    ./update.sh --yes         the same, without asking
#    ./update.sh --schedule    a weekly check in your crontab
#                              (Sunday 04:30); --unschedule removes it
#
#  Only releases are offered: versions brought up and tested together
#  before they were published. Never the newest commit on main.
#  What the weekly check does is UPDATE_MODE in .env:
#    notify  one ntfy message per new release (the default)
#    auto    installs it, then tells you how it went. Never a release
#            with "Action needed", never one less than 3 days old
#    off     nothing
#  It contacts GitHub only, and sends nothing about you.
# ============================================================
set -uo pipefail
cd "$(dirname "$0")" || exit 1
# shellcheck source=lib/detect.sh
. lib/detect.sh
# shellcheck source=lib/release.sh
. lib/release.sh

# Everything runs from main, read in full before it starts: this file
# is replaced by the update itself, and bash reads scripts as it goes.
main() {
  MODE=update; ASSUME_YES=0; NO_BACKUP=0
  for a in "$@"; do case "$a" in
    --check)      MODE=check ;;
    --cron)       MODE=cron ;;
    --schedule)   MODE=schedule ;;
    --unschedule) MODE=unschedule ;;
    --yes|-y)     ASSUME_YES=1 ;;
    --no-backup)  NO_BACKUP=1 ;;
    -h|--help) sed -n '2,20p' "$0" | sed 's/^# \{0,2\}//'; exit 0 ;;
    *) echo "unknown option: $a (try --help)" >&2; exit 2 ;;
  esac; done

  ENV_FILE=".env"
  LOG_DIR="./update-logs"
  STAMP="$(date +%F_%H%M)"
  # Not exported: setup.sh and compose must read the .env that is on
  # disk after setup.sh rewrote it, not a copy from before.
  # shellcheck source=/dev/null  # generated by setup.sh, not in the repo
  [ -r "$ENV_FILE" ] && . "./$ENV_FILE"

  case "$MODE" in
    check)      check_run ;;
    cron)       cron_run ;;
    schedule|unschedule) schedule_run ;;
    update)
      banner "anteiku $S_DOT update" "the newest tested release, with a backup first"
      do_update; exit $? ;;
  esac
}

# ------------------------------------------------------------ --check
check_run() {
  local old changes action
  old="$(release_current)"
  kv "This install" "${old:-unknown}"
  if ! release_latest; then err "Could not ask GitHub for the newest release."; exit 2; fi
  kv "Newest release" "$REL_TAG"
  if [ -n "$old" ] && ! version_gt "$REL_TAG" "$old"; then
    ok "Up to date."; exit 0
  fi
  changes="$(release_changelog "$REL_TAG" | changelog_since "${old:-0.0.0}" "$REL_TAG")"
  action="$(action_needed <<< "$changes")"
  warn "Anteiku $REL_TAG is available."
  if [ -z "$changes" ]; then note "Could not read its changelog."
  elif [ -n "$action" ]; then
    note "Action needed:"
    while IFS= read -r l; do note "  $l"; done <<< "$action"
  else note "Action needed: none."
  fi
  note "Changelog: $ANTEIKU_RELEASES/tag/$REL_TAG"
  note "To update:  ./update.sh"
  exit 1
}

# ------------------------------------------------------------ update
# Returns 0 when updated or already up to date, 1 on failure, 3 when
# the release needs you and this run is unattended. Sets OLD, NEW and
# RESULT (a short summary for a notification).
UNATTENDED=0
OLD=""; NEW=""; OLD_REF=""; RESULT=""; BACKUP_AT=""

rollback_cmds() {
  printf 'cd %q\ngit reset --keep %s\n./setup.sh --yes\ndocker compose up -d\n' "$PWD" "$OLD_REF"
}

stopped() {   # what failed; after the checkout moved, print the way back
  err "Stopped: $1"
  if [ "${2:-}" = moved ]; then
    # Files are at the new release, containers maybe not: doctor.sh says
    # so until you go back or a later update succeeds.
    mkdir -p "$LOG_DIR" && { echo "$NEW"; rollback_cmds; } > "$LOG_DIR/failed"
    note "To go back to ${OLD:-the previous version} ($OLD_REF), as it was before:"
    while IFS= read -r l; do printf '       %s%s%s\n' "$C_B$C_INF" "$l" "$C_RST"; done < <(rollback_cmds)
    note "That does not roll back databases. If a service already upgraded"
    note "its database, restore it from ${BACKUP_AT:-your last backup} (docs/backups.md)."
    RESULT="Stopped at: $1
To go back to ${OLD:-the previous version}:
$(rollback_cmds)
Databases: restore from ${BACKUP_AT:-your last backup} if needed."
  else
    note "Nothing was changed."
    RESULT="Stopped at: $1
Nothing was changed."
  fi
  return 1
}

do_update() {
  local changes action dirty ans slog
  h1 "Before updating"
  git rev-parse --is-inside-work-tree >/dev/null 2>&1 \
    || { err "This folder is not a git checkout."; note "update.sh moves it to a release with git. Clone the repo with git to use it."; RESULT="not a git checkout"; return 1; }
  [ -r "$ENV_FILE" ] || { err "No $ENV_FILE: run ./setup.sh first."; RESULT="no $ENV_FILE"; return 1; }
  have docker || { err "Docker not found."; RESULT="Docker not found"; return 1; }

  # A pull on top of edited files ends half-merged. Refuse, and say how
  # to keep the edits. .env, appdata and logs are ignored by git.
  dirty="$(git status --porcelain --untracked-files=no)"
  if [ -n "$dirty" ]; then
    err "Files from the repo have local changes:"
    while IFS= read -r l; do note "  ${l:3}"; done <<< "$dirty"
    note ""
    note "An update would have to merge them into the new release. Keep"
    note "them aside, update, then bring them back:"
    note "  git stash  &&  ./update.sh  &&  git stash pop"
    note "To run another version of a service, don't edit stacks/: set"
    note "<SERVICE>_VERSION in .env instead (docs/updating.md)."
    RESULT="local changes to tracked files: $(cut -c4- <<< "$dirty" | tr '\n' ' ')
Nothing was changed."
    return 1
  fi
  ok "no local changes to tracked files"

  OLD="$(release_current)"; OLD_REF="$(git rev-parse --short HEAD)"
  kv "This install" "${OLD:-unknown} ($OLD_REF)"
  release_latest || { stopped "could not ask GitHub for the newest release"; return 1; }
  kv "Newest release" "$REL_TAG"
  if [ -n "$OLD" ] && ! version_gt "$REL_TAG" "$OLD"; then
    ok "Up to date."; RESULT="up to date ($OLD)"; return 0
  fi
  NEW="$REL_TAG"

  changes="$(release_changelog "$NEW" | changelog_since "${OLD:-0.0.0}" "$NEW")"
  [ -n "$changes" ] || { stopped "could not read the changelog of $NEW"; return 1; }
  action="$(action_needed <<< "$changes")"
  h1 "What changes: ${OLD:-?} → $NEW"
  while IFS= read -r l; do printf '    %s\n' "$l"; done <<< "$changes"
  echo
  if [ -n "$action" ]; then
    warn "This release needs something from you: read Action needed above."
    if [ "$UNATTENDED" -eq 1 ]; then RESULT="needs you"; return 3; fi
  fi
  if [ "$ASSUME_YES" -eq 0 ]; then
    if [ ! -t 0 ]; then stopped "not a terminal, so nothing to ask: run with --yes"; return 1; fi
    printf '  Update to %s? Backup first, then the new release. %s[y/N]%s ' "$NEW" "$C_B" "$C_RST"
    read -r ans || ans=""
    case "$ans" in [yY]*) ;; *) info "Stopped. Nothing was changed."; RESULT="declined"; return 0 ;; esac
  fi

  h1 "1/5  Backup"
  if [ "$NO_BACKUP" -eq 1 ] && [ "$UNATTENDED" -eq 0 ]; then
    warn "--no-backup: no backup made. Most apps convert their database on"
    note "first start and can't convert it back. You chose to go without."
  elif [ -z "${BACKUP_DEST:-}" ]; then
    err "No backup destination. Set BACKUP_DEST in .env (docs/backups.md)."
    note "Or, deliberately, update without one:  ./update.sh --no-backup"
    stopped "no BACKUP_DEST for the backup"; return 1
  else
    ./scripts/backup.sh || { stopped "the backup failed (output above)"; return 1; }
    BACKUP_AT="$BACKUP_DEST/$(date +%F)"
  fi

  h1 "2/5  Release $NEW"
  git fetch --quiet --tags origin || { stopped "git fetch from origin"; return 1; }
  git rev-parse -q --verify "refs/tags/$NEW^{commit}" >/dev/null \
    || { stopped "origin has no tag $NEW (a fork? git remote -v)"; return 1; }
  git merge --ff-only --quiet "$NEW" \
    || { note "This checkout has commits of its own, so moving to $NEW would"; note "need a merge. Update by hand: docs/updating.md."; stopped "git merge --ff-only $NEW"; return 1; }
  ok "files now at $NEW"

  h1 "3/5  setup.sh"
  mkdir -p "$LOG_DIR"; slog="$LOG_DIR/setup-$STAMP.log"
  # Keeps every setting, password and override; adds what the release needs.
  if ! NO_COLOR=1 ./setup.sh --yes > "$slog" 2>&1; then
    tail -n 15 "$slog" | sed 's/^/    /'
    stopped "./setup.sh --yes (log: $slog)" moved; return 1
  fi
  ok "config refreshed (log: $slog)"
  grep -h 'held at a version override' "$slog" | sed 's/^ *//; s/^/    /'

  h1 "4/5  Images"
  docker compose pull --quiet || { stopped "docker compose pull" moved; return 1; }
  ok "pulled"

  h1 "5/5  Restart"
  docker compose up -d || { stopped "docker compose up -d" moved; return 1; }
  echo
  docker compose ps --format 'table {{.Name}}\t{{.State}}\t{{.Status}}' | sed 's/^/    /'
  echo
  rm -f "$LOG_DIR/failed"
  ok "Updated: ${OLD:-?} → $NEW"
  note "Give it a minute, then check your services. If one misbehaves,"
  note "the way back to ${OLD:-the previous version}:"
  while IFS= read -r l; do printf '       %s%s%s\n' "$C_B$C_INF" "$l" "$C_RST"; done < <(rollback_cmds)
  [ -n "$BACKUP_AT" ] && note "Databases: restore from $BACKUP_AT (docs/backups.md)."
  RESULT="$(docker compose ps --format '{{.Name}} {{.State}}' 2>/dev/null)"
  return 0
}

# ------------------------------------------------------------ --cron
# Password to curl on stdin (-K -), never on the command line, where
# any user on the machine can read it in the process list.
notify() {   # priority tags title body
  [ -n "${NTFY_URL:-}" ] || { echo "no ntfy in .env, not sent: $3"; return 0; }
  { if [ -n "${NTFY_USER:-}" ] && [ -n "${NTFY_PASS:-}" ]; then
      printf 'user = "%s"\n' "$(printf '%s:%s' "$NTFY_USER" "$NTFY_PASS" | sed 's/\\/\\\\/g; s/"/\\"/g')"
    fi; } | curl -fsS -o /dev/null --max-time 20 --retry 4 --retry-connrefused --retry-delay 15 -K - \
      -H "Title: $3" -H "Priority: $1" -H "Tags: $2" -H "Click: $ANTEIKU_RELEASES/tag/$NEW" \
      --data-binary "$4" "$NTFY_URL/${NTFY_TOPIC:-homelab}" \
    || { echo "could not send: $3"; return 1; }
  echo "sent: $3"
}

cron_run() {
  local mode="${UPDATE_MODE:-notify}" changes action age body rc min_age=$((3*86400))
  mkdir -p "$LOG_DIR" || exit 1
  find "$LOG_DIR" -maxdepth 1 -name '*.log' -mtime +180 -delete 2>/dev/null
  exec >> "$LOG_DIR/update-$STAMP.log" 2>&1
  echo "== $(date -Is) weekly check, UPDATE_MODE=$mode"
  case "$mode" in
    off) echo "off: nothing to do"; exit 0 ;;
    notify|auto) ;;
    *) echo "UPDATE_MODE=$mode is not notify, auto or off: using notify"; mode=notify ;;
  esac

  OLD="$(release_current)"
  release_latest || { echo "could not ask GitHub for the newest release"; exit 1; }
  if [ -n "$OLD" ] && ! version_gt "$REL_TAG" "$OLD"; then echo "up to date ($OLD)"; exit 0; fi
  NEW="$REL_TAG"
  changes="$(release_changelog "$NEW" | changelog_since "${OLD:-0.0.0}" "$NEW")"
  [ -n "$changes" ] || { echo "could not read the changelog of $NEW"; exit 1; }
  action="$(action_needed <<< "$changes")"

  if [ "$mode" = auto ] && [ -z "$action" ]; then
    age=$(( $(date +%s) - $(date -d "$REL_DATE" +%s 2>/dev/null || date +%s) ))
    if [ "$age" -lt "$min_age" ]; then
      echo "$NEW is $((age / 3600))h old; auto installs releases at least 3 days old. Next week."
      exit 0
    fi
    UNATTENDED=1; ASSUME_YES=1
    do_update; rc=$?
    if [ "$rc" -eq 0 ]; then
      notify default white_check_mark "Anteiku updated to $NEW" "${OLD:-?} -> $NEW
$RESULT
Changelog: $ANTEIKU_RELEASES/tag/$NEW"
    else
      notify urgent rotating_light "Anteiku update to $NEW FAILED" "$RESULT
Log: $PWD/${LOG_DIR#./}/update-$STAMP.log"
    fi
    exit "$rc"
  fi

  # notify, or auto with a release that needs you: say so once.
  if [ "$(cat "$LOG_DIR/notified" 2>/dev/null)" = "$NEW" ]; then echo "already told about $NEW"; exit 0; fi
  body="Tested release $NEW is out. This install: ${OLD:-unknown}."
  if [ -n "$action" ]; then
    body="$body
Action needed:
$action"
    [ "$mode" = auto ] && body="$body
Not installed automatically: it needs you."
  fi
  body="$body
Changelog: $ANTEIKU_RELEASES/tag/$NEW
To update: cd $PWD && ./update.sh"
  if notify default package "Anteiku $NEW available" "$body"; then
    echo "$NEW" > "$LOG_DIR/notified"
  fi
  exit 0
}

# ------------------------------------------------------------ --schedule
# One line in your own crontab, marked with this folder, so it can be
# found again and two installs never touch each other's line.
CRONTAB="${ANTEIKU_CRONTAB:-crontab}"   # overridable for testing only

schedule_run() {
  local tag="# anteiku-update $PWD" line cur rc keep
  case "$PWD" in *%*) err "cron can't run a path with % in it: $PWD"; exit 1 ;; esac
  have "${CRONTAB%% *}" || { err "crontab not found."; note "Install cron (sudo apt install cron), or run ./update.sh --check now and then."; exit 1; }
  cur="$($CRONTAB -l 2>/dev/null)"; rc=$?
  if [ "$rc" -ne 0 ] && $CRONTAB -l 2>&1 | grep -qv '^no crontab'; then
    err "Could not read your crontab. Left it alone."; exit 1
  fi
  keep="$(awk -v t="$tag" 'substr($0, length($0) - length(t) + 1) != t' <<< "$cur")"
  if [ "$MODE" = schedule ]; then
    line="30 4 * * 0 cd $(printf %q "$PWD") && ./update.sh --cron  $tag"
    printf '%s\n' "${keep:+$keep
}$line" | $CRONTAB - || { err "crontab refused the new line."; exit 1; }
    ok "Weekly check scheduled: Sundays at 04:30."
    note "$line"
    note "What it does is UPDATE_MODE in .env: now ${UPDATE_MODE:-notify}."
    note "Logs: ${LOG_DIR#./}/. Remove it with ./update.sh --unschedule"
  else
    if [ "$keep" = "$cur" ]; then ok "No weekly check was scheduled for this folder."; exit 0; fi
    printf '%s\n' "$keep" | sed '/./,$!d' | $CRONTAB - || { err "crontab refused the change."; exit 1; }
    ok "Weekly check removed."
  fi
  exit 0
}

main "$@"; exit
